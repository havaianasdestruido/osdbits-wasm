const UNKNOWN_GLYPH_ART: readonly string[] = ["#####", "#...#", "..#..", "..#..", "..#..", ".....", "..#.."];

/** Each glyph row packed into the low 5 bits (MSB = leftmost pixel). */
export type GlyphBitmap = Uint8Array;

function packGlyph(rows: readonly string[]): GlyphBitmap {
  const out = new Uint8Array(GLYPH_HEIGHT);
  for (let r = 0; r < GLYPH_HEIGHT; r++) {
    const line = rows[r] ?? ".....";
    let bits = 0;
    for (let c = 0; c < GLYPH_WIDTH; c++) {
      bits = (bits << 1) | (line.charAt(c) === "#" ? 1 : 0);
    }
    out[r] = bits;
  }
  return out;
}

const PACKED = new Map<string, GlyphBitmap>();
for (const [ch, rows] of Object.entries(GLYPH_ART)) {
  PACKED.set(ch, packGlyph(rows));
}
const UNKNOWN_PACKED = packGlyph(UNKNOWN_GLYPH_ART);

/** Maps characters that the shell sometimes receives from the core to ASCII. */
const FALLBACK_REPLACEMENTS: Readonly<Record<string, string>> = {
  "\u2014": "-", // em dash
  "\u2013": "-", // en dash
  "\u2022": "*", // bullet
  "\u25b8": ">", // small right-pointing triangle
  "\u2192": ">", // rightwards arrow
  "\u2026": "...", // horizontal ellipsis
  "\u00b7": "*", // middle dot
};

/** Returns the packed bitmap for one character (folded to upper case). */
export function glyphFor(ch: string): GlyphBitmap {
  const folded = (FALLBACK_REPLACEMENTS[ch] ?? ch).toUpperCase();
  if (folded.length !== 1) return UNKNOWN_PACKED;
  return PACKED.get(folded) ?? UNKNOWN_PACKED;
}

/** Returns true when the font has a dedicated glyph for `ch` (after folding). */
export function hasGlyph(ch: string): boolean {
  const folded = (FALLBACK_REPLACEMENTS[ch] ?? ch).toUpperCase();
  return folded.length === 1 && PACKED.has(folded);
}

/** ASCII printable range that the shell is expected to be able to display. */
export const FONT_PRINTABLE_CHARSET = (() => {
  let out = "";
  for (let code = 0x20; code <= 0x7e; code++) {
    out += String.fromCharCode(code);
  }
  return out;
})();

/** Exposed for tests and the in-app design sheet. */
export function glyphRowsForDebug(ch: string): readonly string[] {
  const rows = GLYPH_ART[ch.toUpperCase()] ?? UNKNOWN_GLYPH_ART;
  return rows;
}
